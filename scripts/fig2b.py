# === 4. МЕТОД МАКСИМАЛЬНОГО ПРАВДОПОДОБИЯ (MLE) ===

# --- Модель А: Степенной закон (Power Law) ---
# Нормированная функция плотности: f(x) = (alpha-1) * xmin^(alpha-1) * x^(-alpha)
def powerlaw_neg_loglik(params):
    alpha = params[0]
    if alpha <= 1: return 1e10
    # Взвешенное логарифмическое правдоподобие
    pdf = (alpha - 1) * (xmin**(alpha - 1)) * (x**(-alpha))
    return -np.sum(w * np.log(pdf + 1e-15))

# --- Модель Б: Логнормальное распределение (Lognormal) ---
# Функция плотности нормируется на промежутке [xmin, inf) через Survival Function (sf)
def lognormal_neg_loglik(params):
    s, scale = params[0], params[1]
    if s <= 0 or scale <= 0: return 1e10
    
    pdf = stats.lognorm.pdf(x, s, scale=scale)
    sf_xmin = stats.lognorm.sf(xmin, s, scale=scale) # Усечение слева
    
    truncated_pdf = pdf / (sf_xmin + 1e-15)
    return -np.sum(w * np.log(truncated_pdf + 1e-15))

